// Generates supabase/rt_seed.sql from src/rt/seed.json (the Excel import + added people).
//   node scripts/rt-seed-sql.mjs
// The SQL inserts with the SAME ids the local preview uses and skips rows that already exist,
// so running it twice never duplicates anything and never overwrites live edits.
import { readFileSync, writeFileSync } from 'node:fs';

const seed = JSON.parse(readFileSync(new URL('../src/rt/seed.json', import.meta.url)));
const COLS = {
  rt_disciplines: ['id', 'name', 'kind', 'sort_order', 'active', 'created_at', 'updated_at'],
  rt_people: ['id', 'discipline_id', 'name', 'role', 'weekly_capacity_hours', 'sort_order', 'active', 'created_at', 'updated_at'],
  rt_projects: ['id', 'name', 'status', 'project_manager', 'start_date', 'target_finish', 'notes', 'active', 'created_at', 'updated_at'],
  rt_tasks: ['id', 'person_id', 'project_id', 'title', 'phase_key', 'start_date', 'due_date', 'hours_per_week', 'status', 'priority', 'notes', 'sort_order', 'active', 'source_row', 'created_at', 'updated_at'],
};
const lit = (v) => (v === null || v === undefined ? 'null' : typeof v === 'boolean' ? String(v) : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
let out = `-- Resource Tracker — initial data (generated by scripts/rt-seed-sql.mjs from src/rt/seed.json).
-- Source: Immersive_Homes_Resource_Planner_v4.xlsx + Amin, Team US, Abhishek.
-- Run AFTER rt_schema.sql, once, in Supabase → SQL Editor. Re-running is safe: existing ids are skipped.
begin;
`;
for (const [t, cols] of Object.entries(COLS)) {
  const rows = seed[t];
  const extra = rows.flatMap((r) => Object.keys(r)).filter((k) => !cols.includes(k));
  if (extra.length) throw new Error(`${t}: fields not in schema: ${[...new Set(extra)].join(', ')}`);
  out += `\n-- ${t}: ${rows.length} rows\ninsert into public.${t} (${cols.join(', ')}) values\n`;
  out += rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n');
  out += '\non conflict (id) do nothing;\n';
}
out += '\ncommit;\n';
writeFileSync(new URL('../supabase/rt_seed.sql', import.meta.url), out);
console.log(`supabase/rt_seed.sql · ${Object.keys(COLS).map((t) => `${t} ${seed[t].length}`).join(' · ')}`);
